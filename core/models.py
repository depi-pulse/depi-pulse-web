class Conversation(models.Model):
    """One WhatsApp chat between the Ministry number and a known sender (Wavz or a provider)."""

    class SenderKind(models.TextChoices):
        WAVZ = "wavz", "Wavz"
        PROVIDER = "provider", "شركة تدريب"

    sender_kind = models.CharField(max_length=10, choices=SenderKind.choices)
    provider = models.ForeignKey(Provider, null=True, blank=True, on_delete=models.SET_NULL)
    display_name = models.CharField(max_length=100)
    phone = models.CharField(max_length=14)
    last_inbound_at = models.DateTimeField()
    last_message_at = models.DateTimeField(db_index=True)
    unread = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["-last_message_at"]

    @property
    def window_open(self):
        return timezone.now() - self.last_inbound_at < timedelta(hours=24)

    @property
    def window_left(self):
        left = timedelta(hours=24) - (timezone.now() - self.last_inbound_at)
        return max(0, int(left.total_seconds() // 3600))


