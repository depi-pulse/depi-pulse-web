class Ticket(models.Model):
    class Priority(models.TextChoices):
        CRITICAL = "critical", "حرجة"
        URGENT = "urgent", "عاجلة"
        HIGH = "high", "عالية"
        MEDIUM = "medium", "متوسطة"
        LOW = "low", "منخفضة"

    class Status(models.TextChoices):
        NEW = "new", "جديدة"
        IN_PROGRESS = "in_progress", "قيد التنفيذ"
        WAITING = "waiting", "في الانتظار"
        RESOLVED = "resolved", "اتحلت"

    class Type(models.TextChoices):
        INCIDENT = "incident", "مشكلة عاجلة"
        COMPLAINT = "complaint", "شكوى"
        REQUEST = "request", "طلب"
        QUESTION = "question", "استفسار"
        SUGGESTION = "suggestion", "اقتراح"

    SLA_HOURS = {"critical": 1, "urgent": 4, "high": 24, "medium": 72, "low": 168}

    code = models.CharField(max_length=15, unique=True)
    conversation = models.ForeignKey(Conversation, null=True, on_delete=models.SET_NULL, related_name="tickets")
    type = models.CharField(max_length=12, choices=Type.choices)
    category = models.CharField(max_length=40)
    priority = models.CharField(max_length=10, choices=Priority.choices)
    status = models.CharField(max_length=12, choices=Status.choices, default=Status.NEW)
    title = models.CharField(max_length=160)
    summary = models.TextField()
    group = models.ForeignKey(Group, null=True, blank=True, on_delete=models.SET_NULL)
    created_at = models.DateTimeField()
    resolved_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at"]

    @property
    def due_at(self):
        return self.created_at + timedelta(hours=self.SLA_HOURS[self.priority])

    @property
    def breached(self):
        end = self.resolved_at or timezone.now()
        return end > self.due_at

    @property
    def sla_used(self):
        end = self.resolved_at or timezone.now()
        total = (self.due_at - self.created_at).total_seconds()
        return min(100, round(100 * (end - self.created_at).total_seconds() / total))


