class Group(models.Model):
    class Mode(models.TextChoices):
        ONLINE = "online", "أونلاين"
        PHYSICAL = "physical", "حضوري"

    code = models.CharField(max_length=20, unique=True)  # CAI5_SWD5_S2
    track = models.ForeignKey(Track, on_delete=models.PROTECT, related_name="groups")
    profile = models.CharField(max_length=120)
    governorate = models.ForeignKey(Governorate, on_delete=models.PROTECT, related_name="groups")
    audience = models.CharField(max_length=1, choices=[("S", "طلبة"), ("G", "خريجين")])
    mode = models.CharField(max_length=10, choices=Mode.choices)
    provider = models.ForeignKey(Provider, on_delete=models.PROTECT, related_name="groups")
    soft_provider = models.ForeignKey(Provider, on_delete=models.PROTECT, related_name="soft_groups")
    english_provider = models.ForeignKey(Provider, on_delete=models.PROTECT, related_name="english_groups")
    technical_instructor = models.ForeignKey(Instructor, null=True, on_delete=models.SET_NULL, related_name="technical_groups")
    soft_instructor = models.ForeignKey(Instructor, null=True, on_delete=models.SET_NULL, related_name="soft_groups")
    english_instructor = models.ForeignKey(Instructor, null=True, on_delete=models.SET_NULL, related_name="english_groups")
    capacity = models.PositiveSmallIntegerField(default=25)
    schedule = models.CharField(max_length=120)
    teams_link_ok = models.BooleanField(default=True)

    class Meta:
        ordering = ["code"]

    def __str__(self):
        return self.code

    @property
    def decoded(self):
        """CAI5_SWD5_S2 -> governorate CAI, round 5, track SWD / profile 5, students, serial 2."""
        loc, trk, aud = self.code.split("_")
        return {
            "parts": [loc[:3], loc[3:], trk, aud],
            "gov": self.governorate.name_ar,
            "round": loc[3:],
            "track": self.track.name_ar,
            "profile": self.profile,
            "audience": "طلبة" if aud[0] == "S" else "خريجين",
            "serial": aud[1:],
        }

    @property
    def enrolled(self):
        return getattr(self, "n_students", None) if hasattr(self, "n_students") else self.students.count()

    @property
    def fill_status(self):
        e, c = self.enrolled, self.capacity
        if e > c:
            return ("أكبر من طاقتها", "err")
        if e == c:
            return ("مكتملة", "gold")
        if e < 15:
            return ("أقل من ١٥", "wait")
        return ("متاحة", "info")


class Applicant(models.Model):
    class Status(models.TextChoices):
        ACCEPTED = "accepted", "مقبول"
        REJECTED = "rejected", "مرفوض"
        POSTPONED = "postponed", "مؤجل"
        UNDER_REVIEW = "under_review", "تحت المراجعة"
        WITHDRAWN = "withdrawn", "منسحب"
        DROPOUT = "dropout", "متسرب"
        BANNED = "banned", "محظور"

    name_ar = models.CharField(max_length=150)
    name_en = models.CharField(max_length=150)
    national_id = models.CharField(max_length=14)
    email = models.EmailField()
    phone = models.CharField(max_length=11)
    gender = models.CharField(max_length=1, choices=[("m", "ذكر"), ("f", "أنثى")])
    governorate = models.ForeignKey(Governorate, on_delete=models.PROTECT, related_name="applicants")
    track = models.ForeignKey(Track, on_delete=models.PROTECT, related_name="applicants")
    status = models.CharField(max_length=14, choices=Status.choices, db_index=True)
    is_graduate = models.BooleanField(default=False)
    university = models.CharField(max_length=120)
    registered_at = models.DateTimeField()
    group = models.ForeignKey(Group, null=True, blank=True, on_delete=models.SET_NULL, related_name="students")
    # attendance aggregates (policy v1), refreshed by the attendance sync job
    lectures = models.PositiveSmallIntegerField(default=0)
    present = models.PositiveSmallIntegerField(default=0)
    partial = models.PositiveSmallIntegerField(default=0)
    absent = models.PositiveSmallIntegerField(default=0)
    excused = models.PositiveSmallIntegerField(default=0)
    late = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["name_ar"]

    def __str__(self):
        return self.name_ar

    @property
    def absence_rate(self):
        counted = self.lectures - self.excused
        return round(100 * (self.absent + 0.5 * self.partial) / counted, 1) if counted else 0.0

    @property
    def warning_level(self):
        r = self.absence_rate
        return 3 if r > 25 else 2 if r >= 20 else 1 if r >= 10 else 0


